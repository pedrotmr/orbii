interface HabitSymbolArtProps {
  symbol: HabitSymbol;
  size: number;
  colors: Palette;
}

export default function HabitSymbolArt({
  symbol,
  size,
  colors,
}: HabitSymbolArtProps) {
  const Icon = artwork[symbol.id] ?? SparkleIcon;
  const earthy = symbol.category === "mind" || symbol.category === "life";
  return (
    <Icon
      size={size}
      weight="duotone"
      color={earthy ? colors.accent : colors.primary}
      duotoneColor={earthy ? colors.accent : colors.primary}
      duotoneOpacity={0.3}
    />
  );
}
